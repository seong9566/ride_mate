SET @run_start = NOW();

-- 이 파일은 한 MySQL 세션에서 실행한다. 같은 서버 시계를 쓰는 업서트의 NOW()는
-- @run_start보다 앞설 수 없으며, 초 단위 경계의 같은 시각 행을 남기기 위해 정리는 < 조건을 쓴다.
INSERT INTO TRAFFIC_PROFILE (AREA_CODE, DAY_OF_WEEK, SLOT_MIN, SOURCE, SPEED_KMH, SAMPLE_DAYS, CREATE_DT, CREATE_USER, UPDATE_DT, UPDATE_USER, DELETE_YN)
WITH bounds AS (
  SELECT MAX(s.SPEED_DATE) AS MAX_SPEED_DATE
  FROM TRAFFIC_HOURLY_SPEED s
  JOIN TRAFFIC_LINK l ON l.TRAFFIC_LINK_ID = s.TRAFFIC_LINK_ID
  WHERE s.DELETE_YN = 0
    AND s.SPEED_KMH > 0
    AND l.SOURCE = 'TOPIS'
    AND l.AREA_CODE = 'DAECHI'
    AND l.DELETE_YN = 0
),
eligible AS (
  SELECT
    l.TRAFFIC_LINK_ID,
    l.AREA_CODE,
    l.DISTANCE_M,
    s.SPEED_DATE AS SAMPLE_DATE,
    WEEKDAY(s.SPEED_DATE) + 1 AS DAY_OF_WEEK,
    s.HOUR_NO,
    s.SPEED_KMH
  FROM TRAFFIC_HOURLY_SPEED s
  JOIN TRAFFIC_LINK l ON l.TRAFFIC_LINK_ID = s.TRAFFIC_LINK_ID
  CROSS JOIN bounds b
  WHERE s.DELETE_YN = 0
    AND s.SPEED_KMH > 0
    AND l.SOURCE = 'TOPIS'
    AND l.AREA_CODE = 'DAECHI'
    AND l.DELETE_YN = 0
    AND l.DISTANCE_M > 0
    AND l.CENTER_DIST_M <= 800
    AND s.SPEED_DATE >= DATE_SUB(DATE_FORMAT(b.MAX_SPEED_DATE, '%Y-%m-01'), INTERVAL 2 MONTH)
    AND s.SPEED_DATE < DATE_ADD(LAST_DAY(b.MAX_SPEED_DATE), INTERVAL 1 DAY)
    AND NOT EXISTS (
      SELECT 1
      FROM HOLIDAY h
      WHERE h.HOLIDAY_DATE = s.SPEED_DATE
        AND h.DELETE_YN = 0
    )
),
ranked AS (
  SELECT
    e.*,
    ROW_NUMBER() OVER (
      PARTITION BY e.TRAFFIC_LINK_ID, e.DAY_OF_WEEK, e.HOUR_NO
      ORDER BY e.SPEED_KMH
    ) AS rn,
    COUNT(*) OVER (
      PARTITION BY e.TRAFFIC_LINK_ID, e.DAY_OF_WEEK, e.HOUR_NO
    ) AS sample_count
  FROM eligible e
),
link_medians AS (
  SELECT TRAFFIC_LINK_ID, AREA_CODE, DISTANCE_M, DAY_OF_WEEK, HOUR_NO, SPEED_KMH AS MEDIAN_SPEED_KMH
  FROM ranked
  WHERE rn = CEIL(sample_count / 2)
),
sample_days AS (
  SELECT AREA_CODE, DAY_OF_WEEK, HOUR_NO, COUNT(DISTINCT SAMPLE_DATE) AS SAMPLE_DAYS
  FROM eligible
  GROUP BY AREA_CODE, DAY_OF_WEEK, HOUR_NO
),
profiles AS (
  SELECT
    m.AREA_CODE,
    m.DAY_OF_WEEK,
    m.HOUR_NO,
    ROUND(SUM(m.DISTANCE_M) / SUM(m.DISTANCE_M / m.MEDIAN_SPEED_KMH), 1) AS SPEED_KMH,
    d.SAMPLE_DAYS
  FROM link_medians m
  JOIN sample_days d
    ON d.AREA_CODE = m.AREA_CODE
   AND d.DAY_OF_WEEK = m.DAY_OF_WEEK
   AND d.HOUR_NO = m.HOUR_NO
  GROUP BY m.AREA_CODE, m.DAY_OF_WEEK, m.HOUR_NO, d.SAMPLE_DAYS
),
slot_offsets AS (
  SELECT 0 AS SLOT_OFFSET
  UNION ALL SELECT 5
  UNION ALL SELECT 10
  UNION ALL SELECT 15
  UNION ALL SELECT 20
  UNION ALL SELECT 25
  UNION ALL SELECT 30
  UNION ALL SELECT 35
  UNION ALL SELECT 40
  UNION ALL SELECT 45
  UNION ALL SELECT 50
  UNION ALL SELECT 55
)
SELECT src.AREA_CODE, src.DAY_OF_WEEK, src.SLOT_MIN, 'MONTHLY', src.SPEED_KMH, src.SAMPLE_DAYS, NOW(), 'SYSTEM', NOW(), 'SYSTEM', 0
FROM (
  SELECT p.AREA_CODE, p.DAY_OF_WEEK, (p.HOUR_NO - 1) * 60 + o.SLOT_OFFSET AS SLOT_MIN, p.SPEED_KMH, p.SAMPLE_DAYS
  FROM profiles p
  CROSS JOIN slot_offsets o
) AS src
ON DUPLICATE KEY UPDATE
  SPEED_KMH = src.SPEED_KMH,
  SAMPLE_DAYS = src.SAMPLE_DAYS,
  UPDATE_DT = NOW(),
  UPDATE_USER = 'SYSTEM',
  DELETE_YN = 0;

UPDATE TRAFFIC_PROFILE
SET SAMPLE_DAYS = 0, UPDATE_DT = NOW(), UPDATE_USER = 'SYSTEM'
WHERE AREA_CODE = 'DAECHI'
  AND SOURCE = 'MONTHLY'
  AND UPDATE_DT < @run_start
  AND SAMPLE_DAYS > 0;
