-- TRAFFIC_LINK — 수집 대상 링크
CREATE TABLE TRAFFIC_LINK (
    TRAFFIC_LINK_ID INT           NOT NULL AUTO_INCREMENT COMMENT '수집 대상 링크 ID',
    SOURCE          VARCHAR(20)   NOT NULL COMMENT '소스 (TOPIS, GITS)',
    AREA_CODE       VARCHAR(20)   NOT NULL COMMENT '학원가 (DAECHI, PYEONGCHON)',
    LINK_ID         VARCHAR(20)   NOT NULL COMMENT '소스의 링크 ID (TOPIS와 GITS는 체계가 다름)',
    ROUTE_ID        VARCHAR(20)   NULL COMMENT 'GITS 도로 ID (도로 단위 수집용, TOPIS는 NULL)',
    ROAD_NAME       VARCHAR(100)  NOT NULL COMMENT '도로명',
    ST_NODE_NAME    VARCHAR(100)  NOT NULL COMMENT '시작 지점명',
    ED_NODE_NAME    VARCHAR(100)  NOT NULL COMMENT '끝 지점명',
    AXIS_DIR        VARCHAR(20)   NULL COMMENT '방향 (TOPIS axis_dir, GITS routeWay)',
    DISTANCE_M      INT           NOT NULL COMMENT '링크 길이(m)',
    CENTER_DIST_M   INT           NULL COMMENT '학원가 중심에서 링크까지 최단 거리(m, TOPIS만 저장)',
    CREATE_DT       DATETIME      NOT NULL COMMENT '생성 일시',
    CREATE_USER     VARCHAR(50)   NOT NULL COMMENT '생성자',
    UPDATE_DT       DATETIME      NOT NULL COMMENT '수정 일시',
    UPDATE_USER     VARCHAR(50)   NOT NULL COMMENT '수정자',
    DELETE_YN       TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    ACTIVE_FLAG     TINYINT GENERATED ALWAYS AS (IF(DELETE_YN = 0, 1, NULL)) VIRTUAL COMMENT '살아 있는 행 표시 (UNIQUE용)',
    PRIMARY KEY (TRAFFIC_LINK_ID),
    UNIQUE KEY UK_TRAFFIC_LINK_01 (SOURCE, LINK_ID, ACTIVE_FLAG),
    INDEX IX_TRAFFIC_LINK_01 (SOURCE, AREA_CODE),
    CONSTRAINT CK_TRAFFIC_LINK_01 CHECK (DISTANCE_M >= 0 AND (CENTER_DIST_M IS NULL OR CENTER_DIST_M >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='수집 대상 링크';

-- TRAFFIC_COLLECT_RUN — 수집 회차
CREATE TABLE TRAFFIC_COLLECT_RUN (
    COLLECT_RUN_ID INT           NOT NULL AUTO_INCREMENT COMMENT '수집 회차 ID',
    SOURCE         VARCHAR(20)   NOT NULL COMMENT '소스 (TOPIS, GITS)',
    RUN_DT         DATETIME      NOT NULL COMMENT '회차 시각(KST, 5분 경계)',
    STATUS         VARCHAR(20)   NOT NULL COMMENT '수집 상태 (OK, PARTIAL, NO_KEY, FAILED)',
    LINK_COUNT     INT           NOT NULL COMMENT '대상 링크 수',
    SAVED_COUNT    INT           NOT NULL COMMENT '저장한 행 수',
    ERROR_MESSAGE  VARCHAR(500)  NULL COMMENT '실패 요약 (키·URL 제외)',
    CREATE_DT      DATETIME      NOT NULL COMMENT '생성 일시',
    CREATE_USER    VARCHAR(50)   NOT NULL COMMENT '생성자',
    UPDATE_DT      DATETIME      NOT NULL COMMENT '수정 일시',
    UPDATE_USER    VARCHAR(50)   NOT NULL COMMENT '수정자',
    DELETE_YN      TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (COLLECT_RUN_ID),
    UNIQUE KEY UK_TRAFFIC_COLLECT_RUN_01 (SOURCE, RUN_DT),
    CONSTRAINT CK_TRAFFIC_COLLECT_RUN_01 CHECK (LINK_COUNT >= 0 AND SAVED_COUNT BETWEEN 0 AND LINK_COUNT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='수집 회차';

-- TRAFFIC_SPEED — 5분 소통 이력
CREATE TABLE TRAFFIC_SPEED (
    TRAFFIC_SPEED_ID    INT         NOT NULL AUTO_INCREMENT COMMENT '5분 소통 이력 ID',
    TRAFFIC_LINK_ID     INT         NOT NULL COMMENT '수집 대상 링크 ID',
    COLLECT_RUN_ID      INT         NOT NULL COMMENT '수집 회차 ID',
    COLLECTED_DT        DATETIME    NOT NULL COMMENT '회차 시각(5분 경계, 한 회차의 행은 모두 같은 값)',
    SOURCE_COLLECTED_DT DATETIME    NULL COMMENT '소스가 준 수집 시각 (GITS collDate, TOPIS는 NULL)',
    SPEED_KMH           SMALLINT    NOT NULL COMMENT '속도 (TOPIS prcs_spd, GITS spd)',
    TRAVEL_SEC          INT         NOT NULL COMMENT '여행시간 초 (TOPIS prcs_trv_time, GITS trvlTime)',
    CREATE_DT           DATETIME    NOT NULL COMMENT '생성 일시',
    CREATE_USER         VARCHAR(50) NOT NULL COMMENT '생성자',
    UPDATE_DT           DATETIME    NOT NULL COMMENT '수정 일시',
    UPDATE_USER         VARCHAR(50) NOT NULL COMMENT '수정자',
    DELETE_YN           TINYINT(1)  NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (TRAFFIC_SPEED_ID),
    UNIQUE KEY UK_TRAFFIC_SPEED_01 (TRAFFIC_LINK_ID, COLLECTED_DT),
    INDEX IX_TRAFFIC_SPEED_01 (COLLECT_RUN_ID),
    INDEX IX_TRAFFIC_SPEED_02 (COLLECTED_DT),
    CONSTRAINT FK_TRAFFIC_SPEED_01 FOREIGN KEY (TRAFFIC_LINK_ID) REFERENCES TRAFFIC_LINK (TRAFFIC_LINK_ID),
    CONSTRAINT FK_TRAFFIC_SPEED_02 FOREIGN KEY (COLLECT_RUN_ID) REFERENCES TRAFFIC_COLLECT_RUN (COLLECT_RUN_ID),
    CONSTRAINT CK_TRAFFIC_SPEED_01 CHECK (SPEED_KMH >= 0 AND TRAVEL_SEC >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='5분 소통 이력';
