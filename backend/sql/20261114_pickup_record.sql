-- T94 픽업 완료 기록: 집에 도착해 픽업 완료를 보낼 때 그날 이동 기록을 시간표 요일마다 하나씩 저장한다
-- 정본: backend/docs/architecture/schema.md, ADR-0027

-- 끝난 계획(PICKUP_PLAN)과 잇지 않는다(ADR-0027). 칸도 FK도 두지 않는다.
-- 시간표 요일마다 살아 있는 기록은 하나다. 다시 저장하면 그 행을 덮어쓴다.
-- 지울 때는 DELETE_YN을 켜고 장소 이름을 빈 문자열로, 좌표를 NULL로 비운다.
CREATE TABLE PICKUP_RECORD (
    PICKUP_RECORD_ID INT           NOT NULL AUTO_INCREMENT COMMENT '픽업 완료 기록 ID',
    USER_ID          INT           NOT NULL COMMENT '계정 ID',
    TIMETABLE_DAY_ID INT           NOT NULL COMMENT '시간표 요일 ID',
    ARRIVE_DT        DATETIME      NOT NULL COMMENT '집 도착 시각',
    TOTAL_MIN        INT           NOT NULL COMMENT '총 소요 분',
    WAIT_MIN         INT           NOT NULL COMMENT '대기 분',
    DEPART_NAME      VARCHAR(100)  NOT NULL COMMENT '출발 장소 이름. 지우면 빈 문자열',
    DEPART_LAT       DECIMAL(10,7) NULL COMMENT '출발 장소 위도. 지우면 NULL',
    DEPART_LNG       DECIMAL(10,7) NULL COMMENT '출발 장소 경도. 지우면 NULL',
    DEPART_DT        DATETIME      NOT NULL COMMENT '출발 시각',
    BOARD_NAME       VARCHAR(100)  NOT NULL COMMENT '탑승 장소 이름. 지우면 빈 문자열',
    BOARD_LAT        DECIMAL(10,7) NULL COMMENT '탑승 장소 위도. 지우면 NULL',
    BOARD_LNG        DECIMAL(10,7) NULL COMMENT '탑승 장소 경도. 지우면 NULL',
    BOARD_DT         DATETIME      NOT NULL COMMENT '탑승 시각',
    AUTO_SAVE_YN     TINYINT(1)    NOT NULL COMMENT '다음부터 묻지 않고 저장 여부',
    CREATE_DT        DATETIME      NOT NULL COMMENT '생성 일시',
    CREATE_USER      VARCHAR(50)   NOT NULL COMMENT '생성자',
    UPDATE_DT        DATETIME      NOT NULL COMMENT '수정 일시',
    UPDATE_USER      VARCHAR(50)   NOT NULL COMMENT '수정자',
    DELETE_YN        TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    ACTIVE_FLAG      TINYINT GENERATED ALWAYS AS (IF(DELETE_YN = 0, 1, NULL)) VIRTUAL COMMENT '살아 있는 행 표시 (UNIQUE용)',
    PRIMARY KEY (PICKUP_RECORD_ID),
    UNIQUE KEY UK_PICKUP_RECORD_01 (TIMETABLE_DAY_ID, ACTIVE_FLAG),
    INDEX IX_PICKUP_RECORD_01 (USER_ID),
    CONSTRAINT FK_PICKUP_RECORD_01 FOREIGN KEY (USER_ID) REFERENCES USER_INFO (USER_ID),
    CONSTRAINT FK_PICKUP_RECORD_02 FOREIGN KEY (TIMETABLE_DAY_ID) REFERENCES TIMETABLE_DAY (TIMETABLE_DAY_ID),
    CONSTRAINT CK_PICKUP_RECORD_01 CHECK (TOTAL_MIN >= 0 AND WAIT_MIN >= 0 AND WAIT_MIN <= TOTAL_MIN),
    CONSTRAINT CK_PICKUP_RECORD_02 CHECK ((DEPART_LAT IS NULL) = (DEPART_LNG IS NULL)),
    CONSTRAINT CK_PICKUP_RECORD_03 CHECK ((BOARD_LAT IS NULL) = (BOARD_LNG IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='픽업 완료 기록';
