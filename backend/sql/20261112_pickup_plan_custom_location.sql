-- 임의 좌표는 공유 지점이 아니라 정원 개념이 없다. 이때 PICKUP_SPOT_ID는 NULL이다.
-- 좌표·이름·도보 경로 선은 계획이 끝나면(익명화) 모두 NULL로 바꾼다.
-- 기존 행은 새 칸이 모두 NULL이라 새 CHECK를 그대로 통과한다.
ALTER TABLE PICKUP_PLAN
    ADD COLUMN CUSTOM_LAT       DECIMAL(10,7) NULL COMMENT '부모가 고른 픽업 위도' AFTER WALK_MIN,
    ADD COLUMN CUSTOM_LNG       DECIMAL(10,7) NULL COMMENT '부모가 고른 픽업 경도' AFTER CUSTOM_LAT,
    ADD COLUMN CUSTOM_NAME      VARCHAR(100)  NULL COMMENT '부모가 고른 픽업 장소 이름' AFTER CUSTOM_LNG,
    ADD COLUMN CUSTOM_WALK_PATH LINESTRING    NULL SRID 4326 COMMENT '학원에서 임의 좌표까지 도보 경로' AFTER CUSTOM_NAME;

-- 장소(지점 또는 임의 좌표)가 있으면 SLOT_DT가 있고 WALK_MIN도 있다.
-- DELETE_YN = 1(끝나서 익명화됨)인 행은 장소 칸이 비어도 SLOT_DT가 남으므로 두 CHECK 모두 예외로 둔다.
ALTER TABLE PICKUP_PLAN
    DROP CHECK CK_PICKUP_PLAN_01,
    DROP CHECK CK_PICKUP_PLAN_02;

ALTER TABLE PICKUP_PLAN
    ADD CONSTRAINT CK_PICKUP_PLAN_01 CHECK (DELETE_YN = 1 OR (SLOT_DT IS NULL) = (PICKUP_SPOT_ID IS NULL AND CUSTOM_LAT IS NULL)),
    ADD CONSTRAINT CK_PICKUP_PLAN_02 CHECK ((PICKUP_SPOT_ID IS NULL AND CUSTOM_LAT IS NULL) OR WALK_MIN IS NOT NULL OR DELETE_YN = 1),
    ADD CONSTRAINT CK_PICKUP_PLAN_03 CHECK ((CUSTOM_LAT IS NULL) = (CUSTOM_LNG IS NULL) AND (CUSTOM_LAT IS NULL) = (CUSTOM_NAME IS NULL)),
    ADD CONSTRAINT CK_PICKUP_PLAN_04 CHECK (PICKUP_SPOT_ID IS NULL OR CUSTOM_LAT IS NULL);
