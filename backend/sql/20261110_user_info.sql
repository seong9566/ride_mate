-- T11 계정 테이블 변경: PARENT → USER_INFO, 운전자 실명, QR user_code
-- 정본: backend/docs/architecture/schema.md · ADR-0012

-- USER_INFO — 운전자 계정 (PARENT에서 이름 변경)
RENAME TABLE PARENT TO USER_INFO;

-- FK가 걸린 칸의 이름 변경은 INPLACE로만 된다. 칸 추가·CHECK 교체와 한 문장에 섞으면 COPY가 되어 실패하므로 나눈다.
ALTER TABLE USER_INFO
    CHANGE COLUMN PARENT_ID USER_ID INT NOT NULL AUTO_INCREMENT COMMENT '운전자 계정 ID',
    RENAME INDEX UK_PARENT_01 TO UK_USER_INFO_01;

ALTER TABLE USER_INFO
    ADD COLUMN USER_NAME VARCHAR(50) NOT NULL COMMENT '운전자 실명' AFTER PHONE_HASH,
    DROP CHECK CK_PARENT_01,
    ADD CONSTRAINT CK_USER_INFO_01 CHECK ((DEST_LAT IS NULL) = (DEST_LNG IS NULL)),
    COMMENT = '운전자 계정';

-- 운전자 계정을 참조하는 칸: PARENT_ID → USER_ID (FK·인덱스 이름에는 PARENT가 없어 그대로 둔다)
ALTER TABLE LOGIN_SESSION
    CHANGE COLUMN PARENT_ID USER_ID INT NOT NULL COMMENT '운전자 계정 ID';

ALTER TABLE CONSENT
    CHANGE COLUMN PARENT_ID USER_ID INT NOT NULL COMMENT '운전자 계정 ID';

ALTER TABLE CHILD
    CHANGE COLUMN PARENT_ID USER_ID INT NOT NULL COMMENT '운전자 계정 ID';

-- PICKUP_PLAN은 CHECK 제약 때문에 칸 이름 변경이 COPY로 돈다. FK를 잠시 풀고 같은 이름으로 다시 건다.
ALTER TABLE PICKUP_PLAN
    DROP FOREIGN KEY FK_PICKUP_PLAN_01;

ALTER TABLE PICKUP_PLAN
    CHANGE COLUMN PARENT_ID USER_ID INT NULL COMMENT '운전자 계정 ID',
    ADD CONSTRAINT FK_PICKUP_PLAN_01 FOREIGN KEY (USER_ID) REFERENCES USER_INFO (USER_ID);

-- QR_LOGIN — 차량은 device_code로 결과를 기다리고, 운전자는 QR의 user_code로 인증한다
ALTER TABLE QR_LOGIN
    CHANGE COLUMN PARENT_ID USER_ID INT NULL COMMENT '인증한 운전자 계정 ID',
    CHANGE COLUMN QR_TOKEN_HASH DEVICE_CODE_HASH CHAR(64) NOT NULL COMMENT '차량이 보관하는 device_code HMAC';

-- 기존 행이 있으면 빈 값끼리 겹쳐 UNIQUE가 실패하므로 NULL 허용으로 먼저 추가한다.
-- 기존 요청은 user_code가 없어 쓸 수 없으므로 행별 고유값을 채우고 삭제 표시한다.
ALTER TABLE QR_LOGIN
    ADD COLUMN USER_CODE_HASH CHAR(64) NULL COMMENT 'QR에 담긴 user_code HMAC' AFTER DEVICE_CODE_HASH;

UPDATE QR_LOGIN
SET USER_CODE_HASH = SHA2(CONCAT('legacy:', QR_LOGIN_ID), 256),
    DELETE_YN = 1,
    UPDATE_DT = NOW(),
    UPDATE_USER = 'SYSTEM';

ALTER TABLE QR_LOGIN
    MODIFY COLUMN USER_CODE_HASH CHAR(64) NOT NULL COMMENT 'QR에 담긴 user_code HMAC',
    ADD UNIQUE KEY UK_QR_LOGIN_02 (USER_CODE_HASH);
