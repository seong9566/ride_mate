-- T07 로그인 세션: 세션 종류(CAR/WEB)와 refresh 교체 직전 값
-- 정본: backend/docs/architecture/schema.md · ADR-0013

ALTER TABLE LOGIN_SESSION
    ADD COLUMN SESSION_TYPE    VARCHAR(20) NOT NULL DEFAULT 'CAR' COMMENT '세션 종류 (CAR, WEB)' AFTER USER_ID,
    ADD COLUMN PREV_TOKEN_HASH CHAR(64)    NULL COMMENT '교체 직전 로그인 토큰 HMAC' AFTER TOKEN_HASH,
    ADD COLUMN ROTATE_DT       DATETIME    NULL COMMENT '토큰 교체 일시' AFTER PREV_TOKEN_HASH,
    ADD INDEX IX_LOGIN_SESSION_02 (PREV_TOKEN_HASH),
    COMMENT = '로그인 세션';

-- 기존 행만 CAR로 채우고 기본값은 없앤다. 새 행은 Service가 종류를 정한다(schema.md: DEFAULT는 DELETE_YN에만)
ALTER TABLE LOGIN_SESSION ALTER COLUMN SESSION_TYPE DROP DEFAULT;
