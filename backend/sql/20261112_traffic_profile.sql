-- 정본: backend/docs/architecture/schema.md

SET @area_code_exists = (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'AREA'
      AND COLUMN_NAME = 'AREA_CODE'
);

SET @area_code_alter = IF(
    @area_code_exists = 0,
    'ALTER TABLE AREA ADD COLUMN AREA_CODE VARCHAR(20) NULL COMMENT ''학원가 코드 (DAECHI, PYEONGCHON)'' AFTER AREA_NAME',
    'SELECT 1'
);

PREPARE area_code_stmt FROM @area_code_alter;
EXECUTE area_code_stmt;
DEALLOCATE PREPARE area_code_stmt;

UPDATE AREA
SET AREA_CODE = CASE AREA_NAME
    WHEN '대치동' THEN 'DAECHI'
    WHEN '평촌' THEN 'PYEONGCHON'
END
WHERE AREA_NAME IN ('대치동', '평촌')
  AND DELETE_YN = 0;

-- TRAFFIC_HOURLY_SPEED — TOPIS 월별 파일의 링크·일자·시간 속도
CREATE TABLE IF NOT EXISTS TRAFFIC_HOURLY_SPEED (
    TRAFFIC_HOURLY_SPEED_ID INT           NOT NULL AUTO_INCREMENT COMMENT '월별 시간 속도 ID',
    TRAFFIC_LINK_ID         INT           NOT NULL COMMENT '수집 대상 링크 ID',
    SPEED_DATE              DATE          NOT NULL COMMENT '속도 일자 (파일의 일자)',
    HOUR_NO                 TINYINT       NOT NULL COMMENT '시간 번호 (파일 열 ~HH시의 HH, 1~24)',
    SPEED_KMH               DECIMAL(5,1)  NOT NULL COMMENT '속도(km/h)',
    CREATE_DT               DATETIME      NOT NULL COMMENT '생성 일시',
    CREATE_USER             VARCHAR(50)   NOT NULL COMMENT '생성자',
    UPDATE_DT               DATETIME      NOT NULL COMMENT '수정 일시',
    UPDATE_USER             VARCHAR(50)   NOT NULL COMMENT '수정자',
    DELETE_YN               TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (TRAFFIC_HOURLY_SPEED_ID),
    UNIQUE KEY UK_TRAFFIC_HOURLY_SPEED_01 (TRAFFIC_LINK_ID, SPEED_DATE, HOUR_NO),
    CONSTRAINT FK_TRAFFIC_HOURLY_SPEED_01 FOREIGN KEY (TRAFFIC_LINK_ID) REFERENCES TRAFFIC_LINK (TRAFFIC_LINK_ID),
    CONSTRAINT CK_TRAFFIC_HOURLY_SPEED_01 CHECK (HOUR_NO BETWEEN 1 AND 24),
    CONSTRAINT CK_TRAFFIC_HOURLY_SPEED_02 CHECK (SPEED_KMH > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='TOPIS 월별 시간 속도';

-- TRAFFIC_PROFILE — 학원가·요일·5분 칸별 혼잡 집계표
CREATE TABLE IF NOT EXISTS TRAFFIC_PROFILE (
    TRAFFIC_PROFILE_ID INT           NOT NULL AUTO_INCREMENT COMMENT '혼잡 집계 ID',
    AREA_CODE          VARCHAR(20)   NOT NULL COMMENT '학원가 코드 (DAECHI, PYEONGCHON)',
    DAY_OF_WEEK        TINYINT       NOT NULL COMMENT '요일 번호 (월 1~일 7)',
    SLOT_MIN           SMALLINT      NOT NULL COMMENT '자정부터 지난 분 (0~1435, 5분 단위)',
    SOURCE             VARCHAR(20)   NOT NULL COMMENT '집계 소스 (COLLECTED, MONTHLY)',
    SPEED_KMH          DECIMAL(5,1)  NOT NULL COMMENT '집계 속도(km/h)',
    SAMPLE_DAYS        SMALLINT      NOT NULL COMMENT '집계 표본 일수. 근거가 없으면 0',
    CREATE_DT          DATETIME      NOT NULL COMMENT '생성 일시',
    CREATE_USER        VARCHAR(50)   NOT NULL COMMENT '생성자',
    UPDATE_DT          DATETIME      NOT NULL COMMENT '수정 일시',
    UPDATE_USER        VARCHAR(50)   NOT NULL COMMENT '수정자',
    DELETE_YN          TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (TRAFFIC_PROFILE_ID),
    UNIQUE KEY UK_TRAFFIC_PROFILE_01 (AREA_CODE, DAY_OF_WEEK, SLOT_MIN, SOURCE),
    CONSTRAINT CK_TRAFFIC_PROFILE_01 CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),
    CONSTRAINT CK_TRAFFIC_PROFILE_02 CHECK (SLOT_MIN BETWEEN 0 AND 1435 AND MOD(SLOT_MIN, 5) = 0),
    CONSTRAINT CK_TRAFFIC_PROFILE_03 CHECK (SPEED_KMH > 0),
    CONSTRAINT CK_TRAFFIC_PROFILE_04 CHECK (SAMPLE_DAYS >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='학원가 요일·시간대 혼잡 집계';
