-- T93 정차 시각·직전 픽업 장소: 장소를 바꾸기 직전의 픽업 장소 칸

-- 직전 장소가 기본 지점이면 PREV_PICKUP_SPOT_ID, 부모가 고른 임의 좌표면 PREV_CUSTOM_* 셋에 담는다.
-- 픽업 장소를 바꾼 적이 없으면 모두 NULL이다. 계획이 끝나면(익명화) 모두 NULL로 바꾼다.
-- 기존 행은 새 칸이 모두 NULL이라 새 CHECK를 그대로 통과한다.
ALTER TABLE PICKUP_PLAN
    ADD COLUMN PREV_PICKUP_SPOT_ID INT           NULL COMMENT '장소를 바꾸기 직전 장소가 기본 지점이면 그 지점' AFTER CUSTOM_WALK_PATH,
    ADD COLUMN PREV_CUSTOM_LAT     DECIMAL(10,7) NULL COMMENT '직전 장소가 부모가 고른 임의 좌표면 그 위도' AFTER PREV_PICKUP_SPOT_ID,
    ADD COLUMN PREV_CUSTOM_LNG     DECIMAL(10,7) NULL COMMENT '직전 장소가 부모가 고른 임의 좌표면 그 경도' AFTER PREV_CUSTOM_LAT,
    ADD COLUMN PREV_CUSTOM_NAME    VARCHAR(100)  NULL COMMENT '직전 임의 좌표의 장소 이름' AFTER PREV_CUSTOM_LNG;

ALTER TABLE PICKUP_PLAN
    ADD CONSTRAINT FK_PICKUP_PLAN_08 FOREIGN KEY (PREV_PICKUP_SPOT_ID) REFERENCES PICKUP_SPOT (PICKUP_SPOT_ID),
    ADD CONSTRAINT CK_PICKUP_PLAN_05 CHECK ((PREV_CUSTOM_LAT IS NULL) = (PREV_CUSTOM_LNG IS NULL) AND (PREV_CUSTOM_LAT IS NULL) = (PREV_CUSTOM_NAME IS NULL)),
    ADD CONSTRAINT CK_PICKUP_PLAN_06 CHECK (PREV_PICKUP_SPOT_ID IS NULL OR PREV_CUSTOM_LAT IS NULL);
