    UNIQUE KEY UK_HOLIDAY_01 (HOLIDAY_DATE, ACTIVE_FLAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='공휴일';

-- PARENT — 부모 계정
CREATE TABLE PARENT (
    PARENT_ID      INT             NOT NULL AUTO_INCREMENT COMMENT '부모 계정 ID',
    PHONE_ENC      VARBINARY(255)  NOT NULL COMMENT '암호화한 휴대폰 번호',
    PHONE_HASH     CHAR(64)        NOT NULL COMMENT '휴대폰 번호 HMAC',
    CALL_NAME      VARCHAR(20)     NULL COMMENT '아이에게 보이는 보호자 호칭',
    CAR_MODEL      VARCHAR(50)     NULL COMMENT '차종',
    CAR_COLOR      VARCHAR(20)     NULL COMMENT '차 색',
    CAR_NO_LAST4   CHAR(4)         NULL COMMENT '차량 번호 뒷자리',
    DEST_ADDRESS   VARCHAR(200)    NULL COMMENT '픽업 후 목적지 주소',
    DEST_LAT       DECIMAL(10,7)   NULL COMMENT '픽업 후 목적지 위도',
    DEST_LNG       DECIMAL(10,7)   NULL COMMENT '픽업 후 목적지 경도',
    AUTO_SEND_YN   TINYINT(1)      NOT NULL COMMENT '링크 자동 발송 여부',
    ARRIVAL_LOG_YN TINYINT(1)      NOT NULL COMMENT '차량 도착 기록 사용 여부',
    WAKE_BEFORE_MIN TINYINT        NOT NULL COMMENT '출발 전 깨우는 시간(분)',
    CREATE_DT      DATETIME        NOT NULL COMMENT '생성 일시',
    CREATE_USER    VARCHAR(50)     NOT NULL COMMENT '생성자',
    UPDATE_DT      DATETIME        NOT NULL COMMENT '수정 일시',
    UPDATE_USER    VARCHAR(50)     NOT NULL COMMENT '수정자',
    DELETE_YN      TINYINT(1)      NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    ACTIVE_FLAG    TINYINT GENERATED ALWAYS AS (IF(DELETE_YN = 0, 1, NULL)) VIRTUAL COMMENT '살아 있는 행 표시 (UNIQUE용)',
    PRIMARY KEY (PARENT_ID),
    UNIQUE KEY UK_PARENT_01 (PHONE_HASH, ACTIVE_FLAG),
    CONSTRAINT CK_PARENT_01 CHECK ((DEST_LAT IS NULL) = (DEST_LNG IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='부모 계정';

-- LOGIN_SESSION — 차량 로그인
