-- AREA — 학원가(서비스 지역)
CREATE TABLE AREA (
    AREA_ID     INT          NOT NULL AUTO_INCREMENT COMMENT '학원가(서비스 지역) ID',
    AREA_NAME   VARCHAR(50)  NOT NULL COMMENT '학원가 이름',
    BOUNDARY    POLYGON      NOT NULL SRID 4326 COMMENT '학원가 구역 경계',
    CREATE_DT   DATETIME     NOT NULL COMMENT '생성 일시',
    CREATE_USER VARCHAR(50)  NOT NULL COMMENT '생성자',
    UPDATE_DT   DATETIME     NOT NULL COMMENT '수정 일시',
    UPDATE_USER VARCHAR(50)  NOT NULL COMMENT '수정자',
    DELETE_YN   TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (AREA_ID),
    SPATIAL INDEX IX_AREA_01 (BOUNDARY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='학원가(서비스 지역)';

-- HOLIDAY — 공휴일
CREATE TABLE HOLIDAY (
    HOLIDAY_ID   INT          NOT NULL AUTO_INCREMENT COMMENT '공휴일 ID',
    HOLIDAY_DATE DATE         NOT NULL COMMENT '공휴일 날짜',
    HOLIDAY_NAME VARCHAR(50)  NOT NULL COMMENT '공휴일 이름',
    CREATE_DT    DATETIME     NOT NULL COMMENT '생성 일시',
    CREATE_USER  VARCHAR(50)  NOT NULL COMMENT '생성자',
    UPDATE_DT    DATETIME     NOT NULL COMMENT '수정 일시',
    UPDATE_USER  VARCHAR(50)  NOT NULL COMMENT '수정자',
    DELETE_YN    TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    ACTIVE_FLAG  TINYINT GENERATED ALWAYS AS (IF(DELETE_YN = 0, 1, NULL)) VIRTUAL COMMENT '살아 있는 행 표시 (UNIQUE용)',
