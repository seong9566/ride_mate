-- TIMETABLE — 시간표
CREATE TABLE TIMETABLE (
    TIMETABLE_ID INT          NOT NULL AUTO_INCREMENT COMMENT '시간표 ID',
    CHILD_ID     INT          NOT NULL COMMENT '아이 ID',
    ACADEMY_ID   INT          NOT NULL COMMENT '학원 ID',
    DISPLAY_NAME VARCHAR(20)  NOT NULL COMMENT '부모가 지정한 학원 이름',
    END_TIME     TIME         NOT NULL COMMENT '하원 시각',
    CREATE_DT    DATETIME     NOT NULL COMMENT '생성 일시',
    CREATE_USER  VARCHAR(50)  NOT NULL COMMENT '생성자',
    UPDATE_DT    DATETIME     NOT NULL COMMENT '수정 일시',
    UPDATE_USER  VARCHAR(50)  NOT NULL COMMENT '수정자',
    DELETE_YN    TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    PRIMARY KEY (TIMETABLE_ID),
    INDEX IX_TIMETABLE_01 (CHILD_ID),
    INDEX IX_TIMETABLE_02 (ACADEMY_ID),
    CONSTRAINT FK_TIMETABLE_01 FOREIGN KEY (CHILD_ID) REFERENCES CHILD (CHILD_ID),
    CONSTRAINT FK_TIMETABLE_02 FOREIGN KEY (ACADEMY_ID) REFERENCES ACADEMY (ACADEMY_ID),
    CONSTRAINT CK_TIMETABLE_01 CHECK (END_TIME BETWEEN '14:00:00' AND '23:30:00'),
    CONSTRAINT CK_TIMETABLE_02 CHECK (MINUTE(END_TIME) % 5 = 0 AND SECOND(END_TIME) = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='시간표';

-- TIMETABLE_DAY — 시간표의 요일
CREATE TABLE TIMETABLE_DAY (
    TIMETABLE_DAY_ID INT          NOT NULL AUTO_INCREMENT COMMENT '시간표 요일 ID',
    TIMETABLE_ID     INT          NOT NULL COMMENT '시간표 ID',
    DAY_OF_WEEK      TINYINT      NOT NULL COMMENT '요일 (1=월, 2=화, 3=수, 4=목, 5=금, 6=토, 7=일)',
    PICKUP_YN        TINYINT(1)   NOT NULL COMMENT '요일별 픽업 여부',
    LAST_PICKUP_DATE DATE         NULL COMMENT '마지막 완료 픽업 날짜',
    CREATE_DT        DATETIME     NOT NULL COMMENT '생성 일시',
    CREATE_USER      VARCHAR(50)  NOT NULL COMMENT '생성자',
    UPDATE_DT        DATETIME     NOT NULL COMMENT '수정 일시',
    UPDATE_USER      VARCHAR(50)  NOT NULL COMMENT '수정자',
    DELETE_YN        TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '삭제 여부',
    ACTIVE_FLAG      TINYINT GENERATED ALWAYS AS (IF(DELETE_YN = 0, 1, NULL)) VIRTUAL COMMENT '살아 있는 행 표시 (UNIQUE용)',
    PRIMARY KEY (TIMETABLE_DAY_ID),
    UNIQUE KEY UK_TIMETABLE_DAY_01 (TIMETABLE_ID, DAY_OF_WEEK, ACTIVE_FLAG),
    CONSTRAINT FK_TIMETABLE_DAY_01 FOREIGN KEY (TIMETABLE_ID) REFERENCES TIMETABLE (TIMETABLE_ID),
    CONSTRAINT CK_TIMETABLE_DAY_01 CHECK (DAY_OF_WEEK BETWEEN 1 AND 7)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='시간표의 요일';

-- TIMETABLE_EXCEPTION — 날짜별 예외
CREATE TABLE TIMETABLE_EXCEPTION (
    TIMETABLE_EXCEPTION_ID INT          NOT NULL AUTO_INCREMENT COMMENT '날짜별 예외 ID',
    TIMETABLE_DAY_ID       INT          NOT NULL COMMENT '시간표 요일 ID',
    TARGET_DATE            DATE         NOT NULL COMMENT '예외 적용 날짜',
